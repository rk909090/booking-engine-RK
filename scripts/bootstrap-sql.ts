/**
 * Builds one SQL script that brings an EMPTY database to the current schema
 * and sample data, for pasting into the Supabase SQL Editor when no direct
 * connection string is available. It contains:
 *   1. every migration in drizzle/, exactly as written;
 *   2. the rows Drizzle's migrator writes to drizzle.__drizzle_migrations,
 *      so a later `npm run db:migrate` skips what already ran;
 *   3. the sample data from src/db/seed-data.ts (produced on PGlite, so it
 *      matches what the tests use).
 *
 * Usage: npx tsx scripts/bootstrap-sql.ts > bootstrap.sql
 */
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import path from "node:path";
import { PGlite } from "@electric-sql/pglite";
import { btree_gist } from "@electric-sql/pglite/contrib/btree_gist";
import { drizzle } from "drizzle-orm/pglite";
import { migrate } from "drizzle-orm/pglite/migrator";
import * as schema from "../src/db/schema";
import { seedSampleData } from "../src/db/seed-data";

const root = path.resolve(import.meta.dirname, "..");
const migrationsDir = path.join(root, "drizzle");
const journal = JSON.parse(readFileSync(path.join(migrationsDir, "meta/_journal.json"), "utf8")) as {
  entries: Array<{ tag: string; when: number }>;
};

function literal(value: unknown): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number" || typeof value === "bigint") return String(value);
  if (typeof value === "boolean") return value ? "TRUE" : "FALSE";
  if (value instanceof Date) return `'${value.toISOString()}'`;
  return `'${String(value).replaceAll("'", "''")}'`;
}

async function dumpTable(client: PGlite, table: string, columns: string[]): Promise<string[]> {
  const { rows } = await client.query<Record<string, unknown>>(
    `select ${columns.map((c) => `"${c}"`).join(", ")} from "${table}" order by 1`,
  );
  return rows.map(
    (row) =>
      `INSERT INTO "${table}" (${columns.map((c) => `"${c}"`).join(", ")}) VALUES (${columns
        .map((c) => literal(row[c]))
        .join(", ")});`,
  );
}

async function main() {
  const out: string[] = ["-- Generated by scripts/bootstrap-sql.ts. Run once on an empty database.", "BEGIN;"];

  for (const entry of journal.entries) {
    const sql = readFileSync(path.join(migrationsDir, `${entry.tag}.sql`), "utf8");
    out.push(`\n-- migration ${entry.tag}`, sql.trim());
  }

  out.push(
    "\n-- Drizzle migration bookkeeping",
    'CREATE SCHEMA IF NOT EXISTS "drizzle";',
    'CREATE TABLE IF NOT EXISTS "drizzle"."__drizzle_migrations" (id SERIAL PRIMARY KEY, hash text NOT NULL, created_at bigint);',
  );
  for (const entry of journal.entries) {
    const sql = readFileSync(path.join(migrationsDir, `${entry.tag}.sql`), "utf8");
    const hash = createHash("sha256").update(sql).digest("hex");
    out.push(`INSERT INTO "drizzle"."__drizzle_migrations" ("hash", "created_at") VALUES ('${hash}', ${entry.when});`);
  }

  const client = new PGlite({ extensions: { btree_gist } });
  const db = drizzle(client, { schema });
  await migrate(db, { migrationsFolder: migrationsDir });
  await seedSampleData(db);

  out.push("\n-- sample data");
  out.push(...(await dumpTable(client, "properties", ["id", "slug", "name"])));
  out.push(
    ...(await dumpTable(client, "unit_types", ["id", "property_id", "slug", "name", "bedrooms", "max_guests", "base_rate"])),
  );
  out.push(...(await dumpTable(client, "units", ["id", "property_id", "unit_type_id", "code", "name"])));
  await client.close();

  out.push("\nCOMMIT;");
  process.stdout.write(out.join("\n") + "\n");
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
